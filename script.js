function mediaAssetUrl(path) {
  return new URL(path, document.baseURI).href;
}

function typewriterText(element, text, speed = 27) {
  const previousTimer = typewriterTimers.get(element);
  if (previousTimer) window.clearTimeout(previousTimer);
  if (reducedMotion) {
    element.textContent = text;
    element.classList.remove('typing');
    return;
  }
  const characters = Array.from(text);
  let index = 0;
  element.textContent = '';
  element.classList.add('typing');
  const writeNext = () => {
    element.textContent = characters.slice(0, index).join('');
    index += 1;
    if (index <= characters.length) {
      typewriterTimers.set(element, window.setTimeout(writeNext, speed));
    } else {
      element.classList.remove('typing');
      typewriterTimers.delete(element);
    }
  };
  writeNext();
}

function nextLoveLineIndex() {
  if (!loveDeck.length) {
    loveDeck = birthdayConfig.loveLines.map((_, i) => i).filter(i => i !== loveIndex);
    for (let i = loveDeck.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [loveDeck[i], loveDeck[j]] = [loveDeck[j], loveDeck[i]];
    }
  }
  return loveDeck.shift();
}

function nextPhotoLine(item, index) {
  const previous = photoLineHistory.get(index);
  const choices = item.lines.filter(line => line !== previous);
  const line = choices[Math.floor(Math.random() * choices.length)] || item.lines[0];
  photoLineHistory.set(index, line);
  return line;
}

function nextVideoLine(item, index) {
  const previous = videoLineHistory.get(index);
  const choices = item.lines.filter(line => line !== previous);
  const line = choices[Math.floor(Math.random() * choices.length)] || item.lines[0];
  videoLineHistory.set(index, line);
  return line;
}

function rotateLoveLine() {
  const line = document.querySelector('#love-line');
  if (!line || !quoteSectionActive || document.hidden) return;
  line.classList.add('out');
  window.clearTimeout(loveTransitionTimer);
  loveTransitionTimer = window.setTimeout(() => {
    if (!quoteSectionActive || document.hidden) { line.classList.remove('out'); return; }
    loveIndex = nextLoveLineIndex();
    line.classList.remove('out');
    typewriterText(line, birthdayConfig.loveLines[loveIndex]);
  }, reducedMotion ? 30 : 420);
}

