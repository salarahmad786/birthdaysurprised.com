function updateBirthdayMusicButton() {
  const button = document.querySelector('#music-button');
  if (!button) return;
  const label = button.querySelector('.music-label');
  button.classList.toggle('playing', birthdayTune.playing && !birthdayTune.pausedForVideo);
  button.classList.toggle('waiting', birthdayTune.enabled && (!birthdayTune.playing || birthdayTune.pausedForVideo));
  if (!birthdayTune.enabled) {
    button.setAttribute('aria-label', 'Play Happy Birthday instrumental');
    button.title = 'Play Happy Birthday instrumental';
    label.textContent = 'birthday tune';
  } else if (birthdayTune.pausedForVideo) {
    button.setAttribute('aria-label', 'Birthday tune paused while the video plays');
    button.title = 'Birthday tune will resume when the video stops';
    label.textContent = 'video playing';
  } else if (birthdayTune.playing) {
    button.setAttribute('aria-label', 'Pause Happy Birthday instrumental');
    button.title = 'Pause Happy Birthday instrumental';
    label.textContent = 'pause tune';
  } else if (birthdayTune.failed) {
    button.setAttribute('aria-label', 'Retry the birthday instrumental');
    button.title = 'The instrumental could not load. Check assets/audio/happy-birthday-instrumental.mp3';
    label.textContent = 'retry tune';
  } else {
    button.setAttribute('aria-label', 'Start Happy Birthday instrumental');
    button.title = birthdayTune.starting ? 'Starting the birthday tune' : 'Tap to start the birthday tune';
    label.textContent = birthdayTune.starting ? 'starting…' : 'tap for tune';
  }
}

function memoryVideoHasAudibleSound() {
  const video = document.querySelector('#memory-video');
  return Boolean(video && !video.paused && !video.ended && !video.muted && video.volume > 0);
}

async function startBirthdayMusic() {
  const audio = birthdayTune.audio;
  if (!birthdayTune.enabled || birthdayTune.playing || birthdayTune.starting) return;
  if (!audio) {
    birthdayTune.failed = true;
    updateBirthdayMusicButton();
    return;
  }
  birthdayTune.starting = true;
  birthdayTune.failed = false;
  updateBirthdayMusicButton();
  try {
    audio.loop = true;
    await audio.play();
    if (!birthdayTune.enabled) {
      audio.pause();
      return;
    }
    birthdayTune.playing = !audio.paused;
    birthdayTune.pausedForVideo = false;
  } catch {
    birthdayTune.playing = false;
    birthdayTune.failed = Boolean(audio.error);
  } finally {
    birthdayTune.starting = false;
    updateBirthdayMusicButton();
  }
}

async function pauseBirthdayMusicForVideo() {
  const audio = birthdayTune.audio;
  if (!birthdayTune.enabled || !memoryVideoHasAudibleSound() || !audio || audio.paused) return;
  birthdayTune.pausedForVideo = true;
  audio.pause();
  updateBirthdayMusicButton();
}

async function resumeBirthdayMusicAfterVideo() {
  const video = document.querySelector('#memory-video');
  const audio = birthdayTune.audio;
  if (!birthdayTune.enabled || memoryVideoHasAudibleSound() || switchingVideo || (video?.ended && videoAutoplayActive)) return;
  if (birthdayTune.pausedForVideo && audio) {
    try {
      await audio.play();
      if (!birthdayTune.enabled) {
        audio.pause();
        return;
      }
      if (memoryVideoHasAudibleSound()) {
        birthdayTune.pausedForVideo = true;
        audio.pause();
        updateBirthdayMusicButton();
        return;
      }
      birthdayTune.playing = !audio.paused;
      birthdayTune.pausedForVideo = false;
      birthdayTune.failed = false;
    } catch {
      birthdayTune.pausedForVideo = false;
      birthdayTune.playing = false;
      birthdayTune.failed = Boolean(audio.error);
    }
    updateBirthdayMusicButton();
    return;
  }
  if (!birthdayTune.playing) await startBirthdayMusic();
}
function updateVideoAudioNote() {
  const video = document.querySelector('#memory-video');
  const note = document.querySelector('#video-audio-note');
  if (!video || !note) return;
  if (video.error) {
    note.textContent = 'This clip could not load. When hosting, upload the complete assets/videos folder beside index.html and keep the video filenames unchanged.';
    return;
  }
  note.textContent = video.muted || video.volume === 0
    ? 'This clip is playing muted. Use the video volume control to hear its original sound.'
    : 'Original video sound is on. The birthday tune pauses while it plays.';
}

async function playMemoryVideo() {
  const video = document.querySelector('#memory-video');
  const note = document.querySelector('#video-audio-note');
  if (!video || !videoAutoplayActive || document.hidden) return;
  if (birthdayTune.enabled && birthdayTune.audio && !birthdayTune.audio.paused) {
    if (!video.paused) video.pause();
    return;
  }
  preparingVideoPlayback = true;
  video.muted = false;
  try {
    await video.play();
    updateVideoAudioNote();
    if (video.muted || video.volume === 0) resumeBirthdayMusicAfterVideo();
  } catch {
    if (!videoAutoplayActive || document.hidden) { preparingVideoPlayback = false; return; }
    video.muted = true;
    try {
      await video.play();
      updateVideoAudioNote();
      if (video.muted || video.volume === 0) resumeBirthdayMusicAfterVideo();
    } catch {
      if (video.error) updateVideoAudioNote();
      else if (note) note.textContent = 'Tap the video play button to start this clip.';
      resumeBirthdayMusicAfterVideo();
    }
  } finally {
    preparingVideoPlayback = false;
  }
}

function setupVideoAutoplay() {
  const section = document.querySelector('#videos');
  const video = document.querySelector('#memory-video');
  const setActive = active => {
    if (active === videoAutoplayActive) return;
    videoAutoplayActive = active;
    if (active) playMemoryVideo();
    else if (!video.paused) video.pause();
  };
  if ('IntersectionObserver' in window) {
    const observer = new IntersectionObserver(entries => {
      const entry = entries[0];
      setActive(entry.isIntersecting && entry.intersectionRatio >= .16);
    }, { threshold: [0, .16, .3] });
    observer.observe(section);
  } else {
    const checkVisibility = () => {
      const rect = section.getBoundingClientRect();
      setActive(rect.top < window.innerHeight * .84 && rect.bottom > window.innerHeight * .16);
    };
    window.addEventListener('scroll', checkVisibility, { passive: true });
    window.addEventListener('resize', checkVisibility);
    checkVisibility();
  }
}

function setupHeroCelebration() {
  const hero = document.querySelector('#home');
  const sash = document.querySelector('#hero-sash');
  let started = false;
  const begin = () => {
    if (started) return;
    started = true;
    createConfetti();
    sash.classList.add('celebrating');
    window.setTimeout(() => sash.classList.remove('celebrating'), 30000);
  };
  if ('IntersectionObserver' in window) {
    const observer = new IntersectionObserver(entries => {
      if (entries[0].isIntersecting && entries[0].intersectionRatio >= .18) {
        begin();
        observer.disconnect();
      }
    }, { threshold: [0, .18] });
    observer.observe(hero);
  } else begin();
}

async function toggleBirthdayMusic(button) {
  if (birthdayTune.enabled && (birthdayTune.playing || birthdayTune.starting || birthdayTune.pausedForVideo)) {
    birthdayTune.enabled = false;
    birthdayTune.playing = false;
    birthdayTune.pausedForVideo = false;
    birthdayTune.audio?.pause();
    updateBirthdayMusicButton();
    if (videoAutoplayActive) playMemoryVideo();
    return;
  }
  birthdayTune.enabled = true;
  birthdayTune.failed = false;
  updateBirthdayMusicButton();
  await startBirthdayMusic();
}

function setupReveal() {
  const items = document.querySelectorAll('.reveal');
  if (!('IntersectionObserver' in window) || reducedMotion) { items.forEach(item => item.classList.add('visible')); return; }
  const observer = new IntersectionObserver(entries => entries.forEach(entry => {
    if (entry.isIntersecting) { entry.target.classList.add('visible'); observer.unobserve(entry.target); }
  }), { threshold: 0.13, rootMargin: '0px 0px -30px 0px' });
  items.forEach(item => observer.observe(item));
}

