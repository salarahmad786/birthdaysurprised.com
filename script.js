function syncSectionTimers() {
  clearInterval(loveTimer); clearInterval(photoTimer);
  if (document.hidden || reducedMotion) return;
  if (quoteSectionActive) {
    const line = document.querySelector('#love-line');
    if (!quoteSectionStarted) {
      quoteSectionStarted = true;
      typewriterText(line, birthdayConfig.loveLines[loveIndex]);
    }
    const bar = document.querySelector('#quote-progress');
    const animateProgress = () => {
      bar.style.transition = 'none'; bar.style.width = '0%';
      requestAnimationFrame(() => {
        if (quoteSectionActive && !document.hidden) { bar.style.transition = 'width 6.4s linear'; bar.style.width = '100%'; }
      });
    };
    animateProgress();
    loveTimer = window.setInterval(() => { rotateLoveLine(); animateProgress(); }, 6400);
  }
  if (albumSectionActive) {
    if (!albumSectionStarted) {
      albumSectionStarted = true;
      typewriterText(document.querySelector('#photo-line'), birthdayConfig.nuzraPhotos[0].lines[0], 25);
    }
    photoTimer = window.setInterval(() => { if (!userPausedAlbum) rotateNuzraPhoto(); }, 8200);
  }
}

function setStorySectionActive(section, active) {
  if (section === 'meaning') {
    if (quoteSectionActive === active) return;
    quoteSectionActive = active;
  } else {
    if (albumSectionActive === active) return;
    albumSectionActive = active;
  }
  syncSectionTimers();
}

function setupStorySectionTiming() {
  const sections = [
    ['meaning', document.querySelector('#meaning')],
    ['album', document.querySelector('#album')]
  ];
  if ('IntersectionObserver' in window) {
    const observer = new IntersectionObserver(entries => entries.forEach(entry => {
      setStorySectionActive(entry.target.id, entry.isIntersecting && entry.intersectionRatio >= .08);
    }), { threshold: [0, .08], rootMargin: '-8% 0px -8% 0px' });
    sections.forEach(([, section]) => observer.observe(section));
    return;
  }
  const updateVisibility = () => sections.forEach(([id, section]) => {
    const rect = section.getBoundingClientRect();
    setStorySectionActive(id, rect.top < window.innerHeight * .9 && rect.bottom > window.innerHeight * .1);
  });
  window.addEventListener('scroll', updateVisibility, { passive: true });
  window.addEventListener('resize', updateVisibility);
  updateVisibility();
}

